
import json
import math
import re


EXPECTED_FIELDS = {
    "current_title",
    "previous_titles",
    "current_company",
    "previous_companies",
    "years_experience",
    "seniority",
    "primary_domain",
    "industries",
    "core_skills",
    "secondary_skills",
    "tools",
    "leadership_experience",
    "key_achievements",
    "location",
    "summary"
}


STRING_FIELDS = {
    "current_title",
    "current_company",
    "seniority",
    "primary_domain",
    "location",
    "summary"
}


LIST_FIELDS = {
    "previous_titles",
    "previous_companies",
    "industries",
    "core_skills",
    "secondary_skills",
    "tools",
    "key_achievements"
}


NULLABLE_FIELDS = {
    "current_title",
    "previous_titles",
    "current_company",
    "previous_companies",
    "years_experience",
    "seniority",
    "industries",
    "core_skills",
    "secondary_skills",
    "tools",
    "leadership_experience",
    "key_achievements",
    "location"
}


def extract_json(generated_text: str) -> dict:
    """
    Extract a JSON object from model-generated text.
    """

    if not isinstance(generated_text, str):
        raise TypeError("Generated output must be a string")

    if not generated_text.strip():
        raise ValueError("Generated output cannot be empty")

    # Remove model thinking blocks, if present.
    text = re.sub(
        r"<think>.*?</think>",
        "",
        generated_text,
        flags=re.DOTALL
    ).strip()

    # Find the beginning of the JSON object.
    start = text.find("{")

    if start == -1:
        raise ValueError("JSON object not found in model output")

    try:
        parsed_data, _ = json.JSONDecoder().raw_decode(text[start:])

    except json.JSONDecodeError as error:
        raise ValueError(
            f"Invalid JSON generated by model: {error}"
        ) from error

    if not isinstance(parsed_data, dict):
        raise ValueError("Model output must be a JSON object")

    return parsed_data


def validate_resume_schema(data: dict) -> dict:
    """
    Validate the 15-field resume extraction schema.
    """

    if not isinstance(data, dict):
        raise TypeError("Parsed output must be a dictionary")

    actual_fields = set(data.keys())

    missing_fields = EXPECTED_FIELDS - actual_fields
    unexpected_fields = actual_fields - EXPECTED_FIELDS

    if missing_fields:
        raise ValueError(
            f"Missing fields: {sorted(missing_fields)}"
        )

    if unexpected_fields:
        raise ValueError(
            f"Unexpected fields: {sorted(unexpected_fields)}"
        )

    for field, value in data.items():

        if value is None:
            if field not in NULLABLE_FIELDS:
                raise ValueError(
                    f"{field} cannot be None"
                )
            continue

        if field in STRING_FIELDS:
            if not isinstance(value, str):
                raise TypeError(
                    f"{field} must be a string or None"
                )

        elif field in LIST_FIELDS:
            if not isinstance(value, list):
                raise TypeError(
                    f"{field} must be a list or None"
                )

            if not all(isinstance(item, str) for item in value):
                raise TypeError(
                    f"Every item in {field} must be a string"
                )

        elif field == "years_experience":
            if isinstance(value, bool):
                raise TypeError(
                    "years_experience must be numeric or None"
                )

            if isinstance(value, str):
                try:
                    value = float(value)
                except ValueError as error:
                    raise ValueError(
                        "years_experience must contain a valid number"
                    ) from error

                data[field] = value

            if not isinstance(value, (int, float)):
                raise TypeError(
                    "years_experience must be numeric or None"
                )

            if not math.isfinite(value) or value < 0:
                raise ValueError(
                    "years_experience must be finite and non-negative"
                )

        elif field == "leadership_experience":
            if not isinstance(value, bool):
                raise TypeError(
                    "leadership_experience must be boolean or None"
                )

    return data


def parse_resume_output(generated_text: str) -> dict:
    """
    Extract, parse and validate model-generated resume JSON.
    """

    parsed_data = extract_json(generated_text)

    validated_data = validate_resume_schema(parsed_data)

    return validated_data
